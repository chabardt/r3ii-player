#!/usr/bin/env python3
"""genres_mb.py — fetch each artist's genres from MusicBrainz into <SD>/Genres.txt.

Explorer (r3player) sorts artists by the genre tags in their files. Untagged artists, or ones
tagged only "Rock", get their (sub)genre from the [musicbrainz] section this script writes;
the device uses it only where the tags give nothing better. Lines above [musicbrainz] are
yours (manual corrections) and are kept as they are.

    python3 scripts/genres_mb.py --sd /media/SDCARD     # card in a reader (or USB mass storage)
    python3 scripts/genres_mb.py --adb                  # R3 plugged in with adb: lists the artists
                                                        # and pushes Genres.txt back to the card

MusicBrainz asks for at most one request per second, so a first run over ~600 artists takes
about 20 minutes. Answers are cached (~/.cache/r3ii-player/musicbrainz.json): re-runs only
look up artists that are new. Only artist names (your Music/ folder names) are sent.
"""
import argparse, json, os, re, subprocess, sys, time, unicodedata, urllib.parse, urllib.request

API = "https://musicbrainz.org/ws/2"
UA = "r3ii-player-genres/1.0 ( https://github.com/chabardt/r3ii-player )"
DEV_SD = "/usr/data/mnt/sd_0"
CACHE = os.path.expanduser("~/.cache/r3ii-player/musicbrainz.json")
SECTION = "[musicbrainz]"
_last = [0.0]

def get(path, **q):
    q["fmt"] = "json"
    url = f"{API}/{path}?{urllib.parse.urlencode(q)}"
    for attempt in range(4):
        wait = 1.1 - (time.time() - _last[0])
        if wait > 0:
            time.sleep(wait)
        _last[0] = time.time()
        try:
            req = urllib.request.Request(url, headers={"User-Agent": UA, "Accept": "application/json"})
            with urllib.request.urlopen(req, timeout=20) as r:
                return json.load(r)
        except urllib.error.HTTPError as e:
            if e.code in (503, 429):          # rate limited: back off
                time.sleep(3 * (attempt + 1)); continue
            if e.code == 404:
                return None
            raise
        except (urllib.error.URLError, TimeoutError):
            time.sleep(3 * (attempt + 1))
    return None

def fold(s):
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode().lower()
    s = re.sub(r"^the\s+", "", s)
    return re.sub(r"[^a-z0-9]+", "", s)

def lookup(name):
    """[genre, ...] for an artist name, most voted first; [] if not found / no genres."""
    res = get("artist", query=f'artist:"{name}"', limit=5)
    if not res or not res.get("artists"):
        return []
    want = fold(name)
    best = None
    for a in res["artists"]:
        names = [a.get("name", ""), a.get("sort-name", "")] + [x.get("name", "") for x in a.get("aliases", []) or []]
        if any(fold(n) == want for n in names if n) and int(a.get("score", 0)) >= 80:
            best = a; break
    if not best:
        return []
    info = get(f"artist/{best['id']}", inc="genres+tags") or {}
    genres = sorted(info.get("genres") or [], key=lambda g: -g.get("count", 0))
    out = [g["name"] for g in genres if g.get("count", 0) > 0][:4]
    if not out:   # no curated genres: fall back to the tags that look like genres
        tags = sorted(info.get("tags") or [], key=lambda g: -g.get("count", 0))
        out = [t["name"] for t in tags if t.get("count", 0) > 0 and len(t["name"]) < 30][:3]
    return out

def artists_sd(sd):
    music = os.path.join(sd, "Music")
    return sorted(d for d in os.listdir(music) if not d.startswith(".") and os.path.isdir(os.path.join(music, d)))

def adb(*args, **kw):
    return subprocess.run(["adb", *args], check=True, capture_output=True, **kw)

ANSI = re.compile(r"\x1b\[[0-9;]*m")
def artists_adb():
    # the R3's busybox ls colours its output (escape codes around every name): turn that off,
    # and strip any left. Folders only: files carry an extension.
    out = adb("shell", f"ls -1 --color=never '{DEV_SD}/Music'").stdout
    names = (ANSI.sub("", l).strip() for l in out.decode("utf-8", "replace").splitlines())
    return sorted(n for n in names if n and not n.startswith(".") and not re.search(r"\.(mp3|flac|m4a|wav|jpg|png|txt|m3u)$", n, re.I))

def merge(existing, lines):
    """keep the manual part of Genres.txt, replace the [musicbrainz] section"""
    head = []
    for l in existing.splitlines():
        if l.strip().lower() == SECTION:
            break
        head.append(l)
    if not head:
        head = ["# Genres for r3player's Explorer. Your corrections go here (they win over file tags):",
                "#   Artist Name = Metal > Viking metal",
                "#   Artist Name = heavy metal; doom metal",
                "#   genre: neue deutsche härte = industrial metal",
                ""]
    return "\n".join(head).rstrip("\n") + "\n\n" + SECTION + "\n" + \
        "# generated by scripts/genres_mb.py from MusicBrainz: used only where the tags say nothing better\n" + \
        "\n".join(lines) + "\n"

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    src = ap.add_mutually_exclusive_group(required=True)
    src.add_argument("--sd", help="mounted SD card (the folder holding Music/)")
    src.add_argument("--adb", action="store_true", help="use the R3 over adb")
    ap.add_argument("--limit", type=int, default=0, help="only the first N artists (testing)")
    a = ap.parse_args()

    names = artists_adb() if a.adb else artists_sd(a.sd)
    if a.limit:
        names = names[:a.limit]
    cache = {}
    if os.path.exists(CACHE):
        cache = json.load(open(CACHE))
    todo = [n for n in names if n not in cache]
    print(f"{len(names)} artists, {len(todo)} to look up (~{len(todo) * 2.3 / 60:.0f} min)")
    for i, n in enumerate(todo, 1):
        try:
            cache[n] = lookup(n)
        except Exception as e:                  # keep going; it is retried next run
            print(f"  {n}: {e}", file=sys.stderr); continue
        print(f"  [{i}/{len(todo)}] {n}: {'; '.join(cache[n]) or '-'}", flush=True)
        if i % 20 == 0:
            os.makedirs(os.path.dirname(CACHE), exist_ok=True); json.dump(cache, open(CACHE, "w"), indent=0)
    os.makedirs(os.path.dirname(CACHE), exist_ok=True); json.dump(cache, open(CACHE, "w"), indent=0)

    lines = [f"{n} = {'; '.join(cache[n])}" for n in names if cache.get(n)]
    found = len(lines)
    if a.adb:
        tmp = os.path.join(os.path.dirname(CACHE), "Genres.txt")
        try:
            adb("pull", f"{DEV_SD}/Genres.txt", tmp)
            existing = open(tmp, encoding="utf-8").read()
        except subprocess.CalledProcessError:
            existing = ""
        open(tmp, "w", encoding="utf-8").write(merge(existing, lines))
        adb("push", tmp, f"{DEV_SD}/Genres.txt")
        adb("shell", "sync")
        dest = f"{DEV_SD}/Genres.txt (on the R3)"
    else:
        path = os.path.join(a.sd, "Genres.txt")
        existing = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
        open(path, "w", encoding="utf-8").write(merge(existing, lines))
        dest = path
    print(f"{found}/{len(names)} artists with MusicBrainz genres -> {dest}")

if __name__ == "__main__":
    main()
